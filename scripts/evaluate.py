"""Small, reproducible rule-based sanity checks; not academic benchmarks."""
import tempfile,sys,json,time,statistics
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from contextcare.core import Store
from contextcare.engine import Assistant
from contextcare.nlp import NLP

ner_examples=[('My name is Trishanth and I met Rahul.',{('Trishanth','PERSON'),('Rahul','PERSON')}),('Email alex@example.org tomorrow at 4 PM.',{('alex@example.org','EMAIL'),('tomorrow','DATE'),('4 PM','TIME')}),('I am preparing for CAT.',{('CAT','EXAM')}),('Call +91 9876543210.',{('+91 9876543210','PHONE')})]
n=NLP();tp=fp=fn=0
for text,gold in ner_examples:
    predicted={(e.text,e.label) for e in n.entities(text)}
    tp+=len(predicted&gold);fp+=len(predicted-gold);fn+=len(gold-predicted)
precision=tp/max(1,tp+fp);recall=tp/max(1,tp+fn)
with tempfile.TemporaryDirectory() as directory:
    s=Store(Path(directory)/'evaluation.db');a=Assistant(s);user=a.auth.register('tester','supersecret123');c=a.conversation(user)
    start=time.perf_counter()
    r=a.chat(user,'My name is Trishanth. I am preparing for CAT and I have a meeting with Rahul tomorrow at 4 PM.',c)
    follow=a.chat(user,'Remind me about that meeting',c)
    name=a.chat(user,'What is my name?',c)
    latency=[r['latency_ms'],follow['latency_ms'],name['latency_ms']]
    pii=['Trishanth','Rahul']
    bytes_data=s.path.read_bytes()
    leakage=sum(any(x.encode() in bytes_data for x in pii) for _ in [0])
    rsuccess=int(bool(a.tasks(user)) and 'meeting' in follow['reply'].lower())
    mem=a.memory.add(user,c,'I am preparing for CAT','preparation')
    target=a.memory.search(user,'CAT exam study',k=3)
    retrieve_hit=int(any(m['id']==mem for m in target))
results={'ner_sanity_examples':len(ner_examples),'ner_precision':round(precision,4),'ner_recall':round(recall,4),'ner_f1':round(2*precision*recall/(precision+recall),4) if precision+recall else 0,'scripted_coreference_success':rsuccess,'scripted_coreference_cases':1,'retrieval_recall_at_3':retrieve_hit,'retrieval_cases':1,'pii_leakage_test_rate':leakage,'pii_test_cases':1,'task_flow_success':rsuccess,'latency_p50_ms':statistics.median(latency),'latency_p95_estimate_ms':sorted(latency)[-1], 'limitations':'Tiny scripted sanity sample, not real-world benchmarking. P95 is maximum of only three measurements.'}
(ROOT/'reports/evaluation.json').write_text(json.dumps(results,indent=2))
text='# Evaluation (actual local run)\n\n'
for k,v in results.items():text+=f'- **{k.replace("_"," ")}**: {v}\n'
text+='\nIntent test metrics are in `reports/intent_metrics.json`, generated by `scripts/train.py` with seed-template group-disjoint splits. Synthetic-only results have severe domain shift and should not be presented as a validated intent benchmark.\n'
(ROOT/'docs/EVALUATION.md').write_text(text)
print(json.dumps(results,indent=2))
